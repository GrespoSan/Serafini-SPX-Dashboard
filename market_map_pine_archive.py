"""Append-only archive of the exact four Streamlit-generated Pine exports.

Opt-in only. This module never recalculates Gamma, changes Pine code, or sends CBOE requests.
A hash-suffixed variant is retained if export inputs legitimately change after first generation.
"""
import hashlib
import json
import re
import time
from datetime import datetime, timezone
from urllib.parse import urlencode, quote
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError


API = "https://www.googleapis.com/drive/v3/files"
UPLOAD = "https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,size,md5Checksum"
SLOTS = {"07:30", "13:30", "15:50", "20:30"}
DAY_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def _request(req):
    for attempt in range(4):
        try:
            with urlopen(req, timeout=45) as response:
                return json.load(response)
        except HTTPError as exc:
            if exc.code not in (429, 500, 502, 503, 504) or attempt == 3:
                raise RuntimeError("Drive HTTP " + str(exc.code)) from exc
        except (URLError, TimeoutError) as exc:
            if attempt == 3:
                raise RuntimeError("Drive network error") from exc
        time.sleep(2 ** attempt)


def _token(cfg):
    keys = ("GOOGLE_DRIVE_CLIENT_ID", "GOOGLE_DRIVE_CLIENT_SECRET",
            "GOOGLE_DRIVE_REFRESH_TOKEN", "MARKET_MAP_DRIVE_PINE_FOLDER_ID")
    if any(not str(cfg.get(k, "")).strip() for k in keys):
        raise RuntimeError("Drive Pine secrets not configured")
    body = urlencode({
        "client_id": cfg["GOOGLE_DRIVE_CLIENT_ID"],
        "client_secret": cfg["GOOGLE_DRIVE_CLIENT_SECRET"],
        "refresh_token": cfg["GOOGLE_DRIVE_REFRESH_TOKEN"],
        "grant_type": "refresh_token",
    }).encode("utf-8")
    result = _request(Request("https://oauth2.googleapis.com/token", data=body))
    return result["access_token"], str(cfg["MARKET_MAP_DRIVE_PINE_FOLDER_ID"])


def _get(token, url):
    return _request(Request(url, headers={"Authorization": "Bearer " + token}))


def _find(token, folder, name):
    # filename and parent are generated by our code, not from user input
    escaped = name.replace("\\", "\\\\").replace("'", "\\'")
    query = "'{}' in parents and name = '{}' and trashed = false".format(
        folder, escaped)
    url = API + "?" + urlencode({
        "q": query, "pageSize": 100,
        "fields": "nextPageToken,files(id,name,size,md5Checksum)",
    })
    items = _get(token, url).get("files", [])
    if len(items) > 1:
        raise RuntimeError("Duplicate Pine archive objects")
    return items[0] if items else None


def _create(token, name, parent, mime, body=None):
    meta = json.dumps({"name": name, "parents": [parent]}).encode("utf-8")
    if body is None:
        req = Request(API + "?fields=id,name", data=json.dumps({
            "name": name, "mimeType": "application/vnd.google-apps.folder",
            "parents": [parent],
        }).encode("utf-8"), method="POST", headers={
            "Authorization": "Bearer " + token,
            "Content-Type": "application/json",
        })
        return _request(req)
    boundary = "market_map_pine_archive"
    payload = (("--" + boundary + "\r\nContent-Type: application/json; charset=UTF-8\r\n\r\n").encode()
               + meta
               + ("\r\n--" + boundary + "\r\nContent-Type: " + mime + "\r\n\r\n").encode()
               + body
               + ("\r\n--" + boundary + "--\r\n").encode())
    return _request(Request(UPLOAD, data=payload, method="POST", headers={
        "Authorization": "Bearer " + token,
        "Content-Type": "multipart/related; boundary=" + boundary,
    }))


def _archive_bytes(token, folder, name, content):
    existing = _find(token, folder, name)
    expected = hashlib.md5(content).hexdigest()
    if existing is None:
        result = _create(token, name, folder, "application/octet-stream", content)
        existing = _get(token, API + "/" + quote(result["id"]) +
                        "?fields=id,name,size,md5Checksum")
    if int(existing.get("size", -1)) != len(content) or existing.get("md5Checksum") != expected:
        raise RuntimeError("Existing Drive content mismatch: " + name)
    return existing["id"]


def archive_pine_exports(day, scripts, sources, basis, cfg):
    """Archive exactly generated Pine bytes, not an approximation or reconstructed backtest.

    Call only after the normal Dashboard exporters and optional news overlay are complete.
    Expected cfg is an explicit trusted server-side Streamlit secrets mapping.
    """
    if not cfg.get("MARKET_MAP_PINE_ARCHIVE_ENABLED", False):
        return {"status": "disabled"}
    day_text = day.isoformat()
    if not DAY_RE.fullmatch(day_text):
        raise ValueError("Invalid day")
    token, root = _token(cfg)
    folder = _find(token, root, day_text)
    if folder is None:
        folder_id = _create(token, day_text, root, "application/vnd.google-apps.folder")["id"]
    else:
        folder_id = folder["id"]
    uploaded = {}
    for slot in ("07:30", "13:30", "15:50", "20:30"):
        code = scripts.get(slot)
        if not isinstance(code, str) or not code:
            continue
        src = sources.get(slot) or {}
        content = code.encode("utf-8")
        sha = hashlib.sha256(content).hexdigest()
        stem = "Serafini_NET_GAMMA_{}_{}_{}".format(
            day_text, slot.replace(":", ""), sha[:12])
        filename = stem + ".pine"
        file_id = _archive_bytes(token, folder_id, filename, content)
        manifest = {
            "schema": "market_map_pine_archive_v1",
            "date_rome": day_text,
            "slot": slot,
            "source": src.get("origin"),
            "source_cboe_timestamp": src.get("cboe_timestamp"),
            "source_download_rome": src.get("download_rome"),
            "es_spx_basis": basis,
            "pine_filename": filename,
            "sha256": sha,
            "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "note": "Pine byte-for-byte from Dashboard after optional macro-news overlay; never a retroactive recomputation",
        }
        # Manifest is append-only and shares the same stable content hash.
        manifest_bytes = json.dumps(manifest, ensure_ascii=False, indent=2).encode("utf-8")
        manifest_name = stem + ".metadata.json"
        # Metadata timestamp is generated once; on reruns an already-present
        # manifest must not be overwritten or revalidated against a new timestamp.
        if _find(token, folder_id, manifest_name) is None:
            _archive_bytes(token, folder_id, manifest_name, manifest_bytes)
        uploaded[slot] = {"file": filename, "drive_id": file_id, "sha256": sha}
    return {"status": "ok", "archived": uploaded, "missing_slots":
            sorted(SLOTS.difference(uploaded))}
